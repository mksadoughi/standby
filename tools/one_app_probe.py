# ---------------------------------------------------------------- the app itself

def states():
    """What macOS tells this process about each permission, without asking."""
    out = {"microphone": None, "input_monitoring": None, "accessibility": None, "screen": None}
    try:
        import objc
        objc.loadBundle("AVFoundation", {}, bundle_path="/System/Library/Frameworks/AVFoundation.framework")
        st = int(objc.lookUpClass("AVCaptureDevice").authorizationStatusForMediaType_("soun"))
        out["microphone"] = {0: "ask", 1: "restricted", 2: "denied", 3: "allowed"}.get(st, str(st))
    except Exception as exc:
        out["microphone"] = "unknown (%s)" % exc.__class__.__name__
    try:
        import Quartz
        out["input_monitoring"] = bool(Quartz.CGPreflightListenEventAccess())
        out["accessibility"] = bool(Quartz.CGPreflightPostEventAccess())
        out["screen"] = bool(Quartz.CGPreflightScreenCaptureAccess())
    except Exception:
        pass
    return out


def mic_level(seconds=0.5):
    """The microphone's level for half a second, in dBFS (nothing kept), or why not."""
    if os.environ.get("STANDBY_NO_DEVICES"):
        return "not measured (tests)"
    try:
        import numpy as np
        import sounddevice as sd
        data = sd.rec(int(16000 * seconds), samplerate=16000, channels=1, dtype="float32")
        sd.wait()
        rms = float(np.sqrt(np.mean(np.square(data)))) if data.size else 0.0
        return round(20 * np.log10(max(rms, 1e-9)), 1)
    except Exception as exc:
        return "failed (%s)" % exc.__class__.__name__


_PROBE = []


def _probe_class():
    """The app's delegate class, made once per process (Objective-C keeps one per name)."""
    if _PROBE:
        return _PROBE[0]
    import objc
    from AppKit import NSApplication, NSObject
    from Foundation import NSBundle

    class Probe(NSObject):
        def init(self):
            self = objc.super(Probe, self).init()
            self.part, self.events, self.level, self.child, self.labels = None, [], None, None, {}
            self.bundle = NSBundle.mainBundle().bundleIdentifier()
            return self

        @objc.python_method
        def note(self, what):
            self.events.append({"at": time.time(), "what": what})
            self.events[:] = self.events[-20:]
            self.write()

        @objc.python_method
        def write(self):
            st = states()
            if st["microphone"] == "allowed" and self.level is None:
                self.level = mic_level()
            r = {"part": self.part, "pid": os.getpid(), "ppid": os.getppid(), "bundle": self.bundle,
                 "xpc_service": os.environ.get("XPC_SERVICE_NAME"), "parent_part": os.environ.get("GRANTTEST_PARENT"),
                 "states": st, "mic_level": self.level, "events": self.events, "at": time.time()}
            path = REPORTS / ("standby-granttest-%s.json" % self.part)
            with open(str(path) + ".tmp", "w") as fh:
                json.dump(r, fh, indent=1)
            os.replace(str(path) + ".tmp", str(path))
            for key, label in self.labels.items():
                label.setStringValue_("%s: %s" % (key.replace("_", " "), _yn(st[key]) if key != "microphone"
                                                  else st[key]))
            return r

        def tick_(self, _timer):
            self.write()

        def askMic_(self, _sender):
            self.note("asked for the microphone")
            self.level = None
            self.level = mic_level()              # opening it is what makes macOS ask

        def askListen_(self, _sender):
            import Quartz
            self.note("asked for Input Monitoring")
            Quartz.CGRequestListenEventAccess()

        def askPost_(self, _sender):
            import Quartz
            self.note("asked for Accessibility")
            Quartz.CGRequestPostEventAccess()

        def askScreen_(self, _sender):
            import Quartz
            self.note("asked for Screen Recording")
            Quartz.CGRequestScreenCaptureAccess()

        def openWindow_(self, _sender):
            self.open_window("menu")

        @objc.python_method
        def open_window(self, why):
            if self.child is not None and self.child.poll() is None:
                self.note("%s: the window is already open (pid %d)" % (why, self.child.pid))
                return
            env = dict(os.environ, GRANTTEST_PARENT="always")
            self.child = subprocess.Popen([str(Path(NSBundle.mainBundle().executablePath())), "--window"],
                                          env=env, stdin=subprocess.DEVNULL)
            self.note("%s: started the window (pid %d)" % (why, self.child.pid))

        def applicationShouldHandleReopen_hasVisibleWindows_(self, _app, _visible):
            self.note("reopen")
            if self.part == "always":
                self.open_window("reopen")
            return True

        def applicationShouldTerminateAfterLastWindowClosed_(self, _app):
            return self.part == "window"

        def applicationWillTerminate_(self, _note):
            self.note("quit")
            os._exit(0)                           # no interpreter shutdown: no crash dialog, ever

        def quit_(self, _sender):
            NSApplication.sharedApplication().terminate_(None)

    _PROBE.append(Probe)
    return Probe


def app_main(argv, headless=False):
    """In the bundle: --always, else the window. headless: build it, write one
    report, never show anything (the tests)."""
    part = "always" if "--always" in argv else "window"
    from AppKit import NSApplication, NSApplicationActivationPolicyAccessory, NSApplicationActivationPolicyRegular
    Probe = _probe_class()

    app = NSApplication.sharedApplication()
    probe = Probe.alloc().init()
    probe.part = part
    if headless:                                  # no delegate, no policy: never a Dock icon or a window
        probe.note("started (headless)")
        return probe.write()
    app.setDelegate_(probe)
    # Before it finishes launching, so the always-on part never shows in the Dock.
    app.setActivationPolicy_(NSApplicationActivationPolicyAccessory if part == "always"
                             else NSApplicationActivationPolicyRegular)
    probe.note("started (%s)" % started_by({"xpc_service": os.environ.get("XPC_SERVICE_NAME"),
                                            "parent_part": os.environ.get("GRANTTEST_PARENT")}))
    _show(app, probe, part)
    if part == "window" and states()["microphone"] == "ask":
        # Not shared after all: opening the microphone is what makes macOS ask, so the
        # split shows as a second prompt the user can see, not only in the report.
        probe.note("the microphone isn't allowed for this part: asking at open")
        probe.level = mic_level()
    from AppKit import NSRunLoop, NSRunLoopCommonModes, NSTimer
    timer = NSTimer.timerWithTimeInterval_target_selector_userInfo_repeats_(2.0, probe, "tick:", None, True)
    NSRunLoop.currentRunLoop().addTimer_forMode_(timer, NSRunLoopCommonModes)
    from PyObjCTools import AppHelper
    AppHelper.runEventLoop()
    return 0


def _show(app, probe, part):
    """The menu bar item (always) or the window, with a menu whose Quit works."""
    from AppKit import (NSBackingStoreBuffered, NSButton, NSMakeRect, NSMenu, NSMenuItem, NSStatusBar,
                        NSTextField, NSVariableStatusItemLength, NSWindow)
    main = NSMenu.alloc().init()
    top = NSMenuItem.alloc().init()
    main.addItem_(top)
    sub = NSMenu.alloc().init()
    sub.addItem_(NSMenuItem.alloc().initWithTitle_action_keyEquivalent_("Quit %s" % NAME, "quit:", "q"))
    top.setSubmenu_(sub)
    app.setMainMenu_(main)
    if part == "always":
        probe.item = NSStatusBar.systemStatusBar().statusItemWithLength_(NSVariableStatusItemLength)
        probe.item.button().setTitle_("Grant test")
        menu = NSMenu.alloc().init()
        head = menu.addItemWithTitle_action_keyEquivalent_("%s: always-on part (pid %d)" % (NAME, os.getpid()),
                                                           None, "")
        head.setEnabled_(False)
        for title, action in (("1. Ask for the microphone", "askMic:"), ("2. Ask for Input Monitoring", "askListen:"),
                              ("3. Ask for Accessibility", "askPost:"), (None, None),
                              ("Open the window", "openWindow:"), (None, None),
                              ("Quit the always-on part", "quit:")):
            if title is None:
                menu.addItem_(NSMenuItem.separatorItem())
                continue
            menu.addItemWithTitle_action_keyEquivalent_(title, action, "").setTarget_(probe)
        probe.item.setMenu_(menu)
        return
    win = NSWindow.alloc().initWithContentRect_styleMask_backing_defer_(
        NSMakeRect(200, 300, 420, 230), 1 | 2 | 4, NSBackingStoreBuffered, False)    # titled, closable, small
    win.setTitle_("%s: window (pid %d)" % (NAME, os.getpid()))
    view, y = win.contentView(), 190
    for key in ("microphone", "input_monitoring", "accessibility", "screen"):
        label = NSTextField.labelWithString_(key)
        label.setFrame_(NSMakeRect(20, y, 380, 20))
        view.addSubview_(label)
        probe.labels[key] = label
        y -= 26
    for i, (title, action) in enumerate((("Ask for the microphone", "askMic:"),
                                         ("Ask for Screen Recording", "askScreen:"))):
        b = NSButton.buttonWithTitle_target_action_(title, probe, action)
        b.setFrame_(NSMakeRect(20 + i * 200, 30, 190, 32))
        view.addSubview_(b)
    probe.win = win
    win.makeKeyAndOrderFront_(None)
    app.activateIgnoringOtherApps_(True)
    probe.write()


# ---------------------------------------------------------------- the sitting, guided

def _reports():
    out = {}
    for part in PARTS:
        try:
            out[part] = json.loads((REPORTS / ("standby-granttest-%s.json" % part)).read_text())
        except (OSError, ValueError):
            out[part] = None
    return out


def _wait_for(pred, most=20.0, step=0.5):
    end = time.time() + most
    while time.time() < end:
        got = pred(_reports())
        if got:
            return got
        time.sleep(step)
    return pred(_reports())


def sitting(full=False, ask=input, say=print, into=None):
    """The user's sitting, guided in Terminal: it builds and starts the test app,
    tells them each click, asks what they saw, and ends with one block to paste
    back. Everything it made is removed at the end, whatever happens."""
    answers, seen = {}, None
    say("Standby's one-app check. About %d minutes. It uses a throwaway app, \"Standby Grant Test\";"
        % (10 if full else 5))
    say("your real Standby, Standby Dictation and their permissions are not touched, and it is all removed at the end.\n")
    try:
        say("Building the test app...")
        build(into)
        agent(True, into)
        _wait_for(lambda r: r["always"], 30)
        say("\n1. In the menu bar, at the top right, click \"Grant test\", then \"1. Ask for the microphone\".")
        say("   macOS asks: \"Standby Grant Test\" would like to access the microphone. Click Allow.")
        say("   (macOS may also say \"Standby Grant Test\" can run in the background: that is this test.)")
        ask("   Press Return here when you have clicked Allow. ")
        _wait_for(lambda r: r["always"] and r["always"]["states"].get("microphone") == "allowed", 15)
        if full:
            say("\n1b. In the same menu, click \"2. Ask for Input Monitoring\". System Settings opens:"
                " turn on \"Standby Grant Test\".")
            say("    Then click \"3. Ask for Accessibility\" and turn it on there too.")
            answers["rows"] = ask("    In each of those two lists, how many \"Standby Grant Test\" rows are there? ")
        say("\n2. In Finder, open your Applications folder (Go > Home, then Applications) and double-click"
            " \"Standby Grant Test\".")
        say("   A small window opens.")
        answers["second_prompt"] = ask("   Did macOS ask for the microphone again? (y/n) ")
        _wait_for(lambda r: r["window"], 15)
        say("\n3. Look at the Dock, then press Command-Tab.")
        answers["icons"] = ask("   How many \"Standby Grant Test\" icons are there in the Dock? ")
        say("\n4. Right-click its Dock icon and choose Quit.")
        answers["stays"] = ask("   Is \"Grant test\" still in the menu bar? (y/n) ")
        if full:
            say("\n5. Double-click \"Standby Grant Test\" in Finder once more.")
            answers["back"] = ask("   Did the window come back, with no prompt? (y/n) ")
        seen = report()
    finally:
        say("\nRemoving the test app and its permissions...")
        clean(into)
    block = ["---- GRANT CHECK ----", seen or "(no report: it stopped early)",
             "second microphone prompt: %s" % answers.get("second_prompt", "?"),
             "Dock icons: %s" % answers.get("icons", "?"),
             "menu bar item stayed after Quit: %s" % answers.get("stays", "?")]
    if full:
        block += ["rows in Input Monitoring / Accessibility: %s" % answers.get("rows", "?"),
                  "window came back on a second open: %s" % answers.get("back", "?")]
    block.append("---- end ----")
    say("\nDone. Please paste everything between the two lines back:\n")
    say("\n".join(block))
    return block


def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__.strip())
        return 0
    cmd, rest = argv[0], argv[1:]
    into = rest[rest.index("--into") + 1] if "--into" in rest else None
    if cmd == "build":
        path, before, now = build(into, change_text="--change-text" in rest)
        print("built %s\n  its mark %s: %s" % (path, now, "the same as before: grants kept" if before == now
                                              else "new: macOS asks again" if before else "first build"))
        return 0
    if cmd == "agent" and rest[:1] in (["on"], ["off"]):
        ok = agent(rest[0] == "on", into)
        print("LaunchAgent %s: %s" % (LABEL, ("loaded" if ok else "FAILED to load") if rest[0] == "on" else "gone"))
        return 0 if ok else 1
    if cmd == "report":
        print(report())
        return 0
    if cmd == "reset":
        return 0 if reset() else 1
    if cmd == "clean":
        clean(into)
        print("gone: the LaunchAgent, %s, its grants and its reports" % app_path(into))
        return 0
    if cmd == "steps":
        print(STEPS)
        return 0
    if cmd == "sitting":
        sitting(full="--full" in rest, into=into)
        return 0
    print(__doc__.strip())
    return 2


