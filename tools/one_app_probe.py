#!/usr/bin/env python3
"""The one-grant-set check: a throwaway app,
"Standby Grant Test" (dev.standby.granttest), built the way install.sh builds
Standby, with two parts in one bundle. It never touches the user's real
Standby or Standby Dictation, nor their grants.

    one_app_probe.py build [--into DIR] [--change-text]   build it (into ~/Applications)
    one_app_probe.py agent on|off                          its LaunchAgent: the always-on part, now
    one_app_probe.py report                                what each part sees, now
    one_app_probe.py reset                                 forget the test app's grants (its id only)
    one_app_probe.py clean                                 all of it gone: agent, app, grants, reports
    one_app_probe.py steps                                 the hands-on, step by step
    one_app_probe.py sitting [--full]                      the hands-on, guided, about 5 minutes (10 with --full)

Inside the app, one executable, two ways to run it, as the app has them:
  --always  the menu bar part, no Dock icon. Its menu asks for the microphone,
            Input Monitoring and Accessibility; "reopen" (a Finder double-click
            while it runs) starts --window as its own child.
  --window  a small window (also: opened with no arguments, from Finder). It asks
            for the microphone and Screen Recording.
Each writes what macOS tells it, every 2 s, to /tmp/standby-granttest-<part>.json.
Nothing is recorded or kept: the microphone is opened for half a second to read
its level. No key is listened to and nothing is typed."""
import json
import os
import plistlib
import shutil
import subprocess
import sys
import time
from pathlib import Path

BUNDLE_ID = "dev.standby.granttest"          # never dev.standby.app or dev.standby.dictation
NAME = "Standby Grant Test"
LABEL = BUNDLE_ID
HERE = Path(__file__).resolve().parent
APPS = Path.home() / "Applications"
AGENTS = Path(os.environ.get("STANDBY_LAUNCH_AGENTS", Path.home() / "Library" / "LaunchAgents"))
REPORTS = Path(os.environ.get("GRANTTEST_REPORTS", "/tmp"))
LOG = REPORTS / "standby-granttest.log"
MIC_TEXT = "Standby Grant Test checks that one app is asked for the microphone once."
MIC_TEXT_CHANGED = "Standby Grant Test checks that one app is asked for the microphone only once."
PARTS = ("always", "window")
STALE = 10.0                                 # a report older than this: that part isn't running


def app_path(into=None):
    return Path(into or APPS) / (NAME + ".app")


def build_dir(into=None):
    """Where it's built, and stays: alias mode runs the entry script from there, and
    the path is part of what's signed, so the same folder every time keeps the mark."""
    return Path(into) / ".granttest-build" if into else Path.home() / "Library" / "Caches" / BUNDLE_ID


def executable(into=None):
    return app_path(into) / "Contents" / "MacOS" / NAME


# ---------------------------------------------------------------- building it

ENTRY = '''# Generated by tools/one_app_probe.py: the %(name)s.app entry point.
import os, site, sys
log = open(%(log)r, "a", buffering=1)
os.dup2(log.fileno(), 1)
os.dup2(log.fileno(), 2)
sys.stdout = sys.stderr = log
site.addsitedir(%(site)r)
sys.path.insert(0, %(tools)r)
sys.executable = %(python)r
import one_app_probe
sys.exit(one_app_probe.app_main(sys.argv[1:]))
'''

SETUP = '''from setuptools import setup
plist = {
    "CFBundleName": %(name)r, "CFBundleDisplayName": %(name)r,
    "CFBundleIdentifier": %(bundle)r,
    "CFBundleShortVersionString": "0.1", "CFBundleVersion": "0.1",
    "LSMinimumSystemVersion": "13.0", "NSHighResolutionCapable": True,
    "NSMicrophoneUsageDescription": %(mic)r,
}
setup(app=["GrantTest.py"], name=%(name)r, options={"py2app": {"alias": True, "argv_emulation": False, "plist": plist}})
'''


def mark(app):
    """What macOS keys an app's grants on, as install.sh's app_mark reads it: the
    ad-hoc signature's CDHash, else its Info.plist's hash; None if there's no app."""
    if not Path(app).is_dir():
        return None
    r = subprocess.run(["codesign", "-dvvv", str(app)], capture_output=True, text=True)
    got = [l.split("=", 1)[1].strip() for l in (r.stdout + r.stderr).splitlines() if l.startswith("CDHash=")]
    if got and got[0]:
        return got[0]
    import hashlib
    return hashlib.sha1((Path(app) / "Contents" / "Info.plist").read_bytes()).hexdigest()


def build(into=None, change_text=False, python=None):
    """Build the test app (py2app, alias mode, as install.sh does) and put it in
    `into`. Returns (path, mark before, mark now)."""
    python = python or sys.executable
    site_dir = subprocess.run([python, "-c", "import sysconfig; print(sysconfig.get_paths()['purelib'])"],
                              capture_output=True, text=True, check=True).stdout.strip()
    work = build_dir(into)
    for old in ("build", "dist"):
        shutil.rmtree(str(work / old), ignore_errors=True)
    work.mkdir(parents=True, exist_ok=True)
    (work / "GrantTest.py").write_text(ENTRY % {"name": NAME, "log": str(LOG), "site": site_dir,
                                                "tools": str(HERE), "python": python})
    (work / "setup.py").write_text(SETUP % {"name": NAME, "bundle": BUNDLE_ID,
                                            "mic": MIC_TEXT_CHANGED if change_text else MIC_TEXT})
    r = subprocess.run([python, "setup.py", "py2app", "-A"], cwd=str(work), capture_output=True, text=True)
    built = work / "dist" / (NAME + ".app")
    if r.returncode != 0 or not built.is_dir():
        raise SystemExit("could not build %s.app:\n%s" % (NAME, (r.stdout + r.stderr)[-2000:]))
    dest = app_path(into)
    before = mark(dest)
    if dest.exists():
        shutil.rmtree(str(dest))
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(built), str(dest))
    return dest, before, mark(dest)


# ---------------------------------------------------------------- its LaunchAgent, its grants

def agent(on, into=None, run=subprocess.run):
    """The always-on part from a LaunchAgent, as Standby's would be (and dictation's is
    today), started now. No KeepAlive: a test app doesn't come back by itself."""
    plist, dom = AGENTS / (LABEL + ".plist"), "gui/%d" % os.getuid()
    if on:
        AGENTS.mkdir(parents=True, exist_ok=True)
        with open(plist, "wb") as fh:
            plistlib.dump({"Label": LABEL, "ProgramArguments": [str(executable(into)), "--always"],
                           "RunAtLoad": True, "ProcessType": "Interactive",
                           "StandardErrorPath": str(LOG)}, fh)
        run(["launchctl", "bootout", "%s/%s" % (dom, LABEL)], capture_output=True)
        return run(["launchctl", "bootstrap", dom, str(plist)], capture_output=True).returncode == 0
    run(["launchctl", "bootout", "%s/%s" % (dom, LABEL)], capture_output=True)
    try:
        plist.unlink()
    except OSError:
        pass
    return True


def reset(run=subprocess.run):
    """Forget every grant of the test app: its bundle id, and no other."""
    assert BUNDLE_ID == "dev.standby.granttest"
    return run(["tccutil", "reset", "All", BUNDLE_ID], capture_output=True).returncode == 0


def clean(into=None, run=subprocess.run):
    agent(False, into, run)
    run(["pkill", "-f", str(executable(into))], capture_output=True)
    app = app_path(into)
    if app.name == NAME + ".app" and app.exists():
        shutil.rmtree(str(app))
    shutil.rmtree(str(build_dir(into)), ignore_errors=True)
    reset(run)
    for part in PARTS:
        try:
            (REPORTS / ("standby-granttest-%s.json" % part)).unlink()
        except OSError:
            pass


# ---------------------------------------------------------------- what each part saw

def started_by(r):
    """How a part was started, in the hands-on's words, from what it recorded."""
    if r.get("parent_part") == "always":
        return "the always-on part (its child)"
    service = r.get("xpc_service") or ""
    if service == LABEL:
        return "launchd (its LaunchAgent)"
    if service.startswith("application."):
        return "Finder or the Dock"
    return "a terminal or a test (%s)" % (service or "no launchd job")


def report(now=None):
    """One line per part: who it is, how it started, what macOS says to it."""
    now = time.time() if now is None else now
    lines = []
    for part in PARTS:
        try:
            r = json.loads((REPORTS / ("standby-granttest-%s.json" % part)).read_text())
        except (OSError, ValueError):
            lines.append("%-7s not seen" % part)
            continue
        age = now - float(r.get("at") or 0)
        st = r.get("states") or {}
        lines.append("%-7s pid %s (parent %s), started by %s%s" % (
            part, r.get("pid"), r.get("ppid"), started_by(r),
            "" if age < STALE else ", NOT RUNNING (last seen %ds ago)" % age))
        lines.append("        bundle %s; microphone %s, input monitoring %s, accessibility %s, screen %s; level %s"
                     % (r.get("bundle"), st.get("microphone"), _yn(st.get("input_monitoring")),
                        _yn(st.get("accessibility")), _yn(st.get("screen")), r.get("mic_level")))
        for ev in r.get("events") or []:
            lines.append("        %s %s" % (time.strftime("%H:%M:%S", time.localtime(ev.get("at") or 0)), ev.get("what")))
    return "\n".join(lines)


def _yn(v):
    return "allowed" if v else "no" if v is not None else "?"


